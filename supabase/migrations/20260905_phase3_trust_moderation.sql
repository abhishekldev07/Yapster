create table if not exists public.moderation_log (
  id bigint generated by default as identity primary key,
  community_id bigint not null references public.communities(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete cascade,
  action_type text not null,
  target_type text not null,
  target_id bigint,
  note text not null default '',
  created_at timestamptz not null default now(),
  constraint moderation_log_action_type_check check (action_type in ('report_resolved', 'report_dismissed', 'post_removed', 'comment_removed', 'member_muted', 'member_unmuted', 'member_banned', 'member_unbanned')),
  constraint moderation_log_target_type_check check (target_type in ('report', 'post', 'comment', 'member')),
  constraint moderation_log_note_length_check check (char_length(note) <= 1200)
);

create index if not exists moderation_log_community_created_idx
  on public.moderation_log (community_id, created_at desc);
